import { randomUUID } from 'node:crypto';
import { test, expect } from '../apoyo/prueba';
import { acceder, irA } from '../apoyo/sesion';

const API = process.env.URL_API ?? 'http://127.0.0.1:8000/api/v1';

test('gasto: validación, guardado exacto, consulta filtrada y anulación con trazabilidad', async ({ page, request }) => {
  const login = await request.post(`${API}/autenticacion/sesion-local`, { data: { codigo_rol: 'administrador_clinica' } });
  expect(login.ok()).toBeTruthy();
  const headers = { Authorization: `Bearer ${(await login.json()).token_acceso}` };
  const descripcion = `Gasto QA sintético ${randomUUID()}`;
  await page.setViewportSize({ width: 1440, height: 900 });
  await acceder(page, 'administradora');
  await irA(page, 'Gastos y caja');
  await page.getByRole('button', { name: 'Registrar gasto', exact: true }).click();
  const ventana = page.getByRole('dialog', { name: 'Registrar gasto', exact: true });
  const guardar = ventana.getByRole('button', { name: 'Registrar gasto', exact: true });
  await guardar.click();
  await expect(ventana.getByRole('alert')).toContainText('Revise');
  await ventana.getByLabel('Descripción', { exact: true }).fill(descripcion);
  await ventana.getByLabel('Importe (USD)', { exact: true }).fill('12.345');
  await guardar.click();
  await expect(ventana.getByRole('alert')).toContainText('dos decimales');
  await ventana.getByLabel('Importe (USD)', { exact: true }).fill('12.34');
  await ventana.getByRole('combobox', { name: 'Categoría *', exact: true }).selectOption({ label: 'Equipamiento' });
  await ventana.getByRole('combobox', { name: 'Método *', exact: true }).selectOption('EFECTIVO');
  const respuesta = page.waitForResponse(r => r.url().endsWith('/gastos') && r.request().method() === 'POST');
  await guardar.click();
  const creada = await respuesta;
  expect(creada.status()).toBe(201);
  expect(creada.request().headers()['idempotency-key']).toBeTruthy();
  const gasto = await creada.json();
  expect(gasto.importe).toBe('12.34');
  expect(gasto.descripcion).toBe(descripcion);
  await expect(ventana).not.toBeVisible();
  const consulta = await request.get(`${API}/gastos?categoria=EQUIPAMIENTO`, { headers });
  expect(consulta.ok()).toBeTruthy();
  expect((await consulta.json()).elementos.find((g: { id: string }) => g.id === gasto.id).importe).toBe('12.34');
  await page.getByRole('form', { name: 'Periodo y filtros' }).getByRole('combobox', { name: 'Categoría', exact: true }).selectOption({ label: 'Equipamiento' });
  await page.getByRole('button', { name: 'Aplicar', exact: true }).click();
  const fila = page.locator('tr').filter({ hasText: descripcion });
  await expect(fila).toBeVisible();
  await fila.getByRole('button', { name: 'Anular', exact: true }).click();
  const anulacion = page.getByRole('dialog', { name: 'Anular gasto', exact: true });
  await anulacion.getByLabel('Motivo', { exact: true }).fill('Corrección sintética de auditoría');
  await anulacion.getByRole('button', { name: 'Anular gasto', exact: true }).click();
  await expect(anulacion).not.toBeVisible();
  await expect(fila).not.toBeVisible();
  const historico = await request.get(`${API}/gastos?categoria=EQUIPAMIENTO&incluir_anulados=true`, { headers });
  expect(historico.ok()).toBeTruthy();
  const guardado = (await historico.json()).elementos.find((g: { id: string }) => g.id === gasto.id);
  expect(guardado.estado).toBe('ANULADO');
  expect(guardado.importe).toBe('12.34');
  expect(guardado.motivo_anulacion).toBe('Corrección sintética de auditoría');
});
